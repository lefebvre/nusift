def figure_decay(path):
    """Raw trajectories: the ingrowth a ranking would hide behind its ordering."""
    rows = read_csv("scenario-decay.csv")
    header_row = list(rows[0].keys())
    times = [float(t) for t in header_row[1:]]

    wanted = ["I-131", "Ba-140", "La-140", "Zr-95", "Cs-137", "Sr-90"]
    series = []
    for name in wanted:
        for row in rows:
            if row["nuclide"] == name:
                values = [float(row[t]) for t in header_row[1:]]
                series.append((name, [(t, v) for t, v in zip(times, values) if v > 0]))
                break

    lo = min(min(v for _, v in pts) for _, pts in series)
    hi = max(max(v for _, v in pts) for _, pts in series)
    w, h = 880, 500
    ax = Axes(84, 800, 86, 330, (times[0], times[-1]), (max(lo, hi * 1e-9), hi * 3), xlog=True, ylog=True)

    parts = []
    exponent_hi = int(math.floor(math.log10(hi * 3)))
    grid = [10.0**e for e in range(exponent_hi - 8, exponent_hi + 1, 2)]
    parts += ax.hgrid(grid, [f"1e{int(math.log10(g))}" for g in grid])
    parts += time_axis(ax, times[0], times[-1])
    series_plot(parts, ax, series)
    parts += ax.frame()

    header(parts, ax, "Atoms against time — 20 kt U-235 thermal fission",
           "`nusift decay` — the trajectories themselves, before any weight is applied")
    parts.append(text(ax.right, ax.bottom + 34, "time after fission →", "muted", 11, "end"))
    notes(parts, ax, [
        "La-140 is not seeded and still peaks near a day: it is grown in by Ba-140, and a curve that only ever falls would be the",
        "signature of a chain that was not solved. This is the one command that applies no weight at all — every other figure here is",
        "this matrix multiplied by something, which is why they can disagree about what matters without disagreeing about the physics.",
    ])
    write(path, w, h, parts, "Nuclide trajectories after fission")
    print(f"  decay: {len(series)} trajectories over {len(times)} samples")


