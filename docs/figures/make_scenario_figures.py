def ranked_bars(parts, left, top, width, rows, value_of, label_of, note_of=None, cls_of=None,
                row_h=22, bar_h=13, label_w=76, value_w=96):
    """Rows in the order given, longest bar normalized to the widest available space.

    Deliberately NOT sorted here: every one of these commands has already chosen an order, and
    that order is usually the point -- a shortlist's build order is not a ranking, and a variance
    fraction is not a share of the answer.
    """
    values = [abs(value_of(r)) for r in rows]
    span = max(values) if values else 1.0
    bar_left = left + label_w
    bar_max = width - label_w - value_w
    for i, row in enumerate(rows):
        y = top + i * row_h
        value = abs(value_of(row))
        cls = cls_of(i, row) if cls_of else f"t{i % 8}"
        parts.append(text(left, y + bar_h - 2, label_of(row), "ink", 11, "start", "500"))
        length = bar_max * (value / span) if span > 0 else 0.0
        parts.append(rect(bar_left, y, max(length, 0.6), bar_h, cls, 0.75, rx=1.5, width=0))
        parts.append(text(bar_left + bar_max + 8, y + bar_h - 2,
                          note_of(row) if note_of else si(value), "muted", 10.5))
    return top + len(rows) * row_h


def _pixel_curve(ax, points):
    """A series as pixel coordinates, ascending in x, for label placement to reason over."""
    return sorted(((ax.x(t), ax.y(v)) for t, v in points), key=lambda p: p[0])


def _at(curve, px):
    """Linear interpolation of a pixel curve at a pixel x, or None outside its range."""
    if px < curve[0][0] or px > curve[-1][0]:
        return None
    for (x0, y0), (x1, y1) in zip(curve, curve[1:]):
        if x0 <= px <= x1:
            if x1 == x0:
                return y0
            return y0 + (y1 - y0) * (px - x0) / (x1 - x0)
    return curve[-1][1]


def place_labels(ax, series, min_gap=14.0, min_dx=48.0, margin=34.0, candidates=41):
    """Anchor each curve's label where that curve is furthest from every other one.

    Labeling each curve at its own maximum is the obvious rule and it fails badly on a decay
    plot: the curves that start highest all peak at the first sample, so every label lands in the
    same corner on top of the others. What makes a label readable is not that its curve is high
    there but that no OTHER curve is near it there, which is what this maximizes.

    Labels are then placed one at a time, and each takes the best position that does not collide
    with one already placed. Moving a label ALONG its own curve is preferred to nudging it off,
    because a label that has been pushed clear of the traffic is also a label that no longer sits
    on the line it names -- which is a worse failure than the crowding it was fixing.
    """
    curves = [_pixel_curve(ax, points) for _, points in series]
    lo, hi = ax.left + margin, ax.right - margin
    xs = [lo + i * (hi - lo) / (candidates - 1) for i in range(candidates)]

    # Each curve's candidate anchors, best separation first.
    options = []
    for i, curve in enumerate(curves):
        scored = []
        for px in xs:
            y = _at(curve, px)
            if y is None:
                continue
            others = [_at(other, px) for j, other in enumerate(curves) if j != i]
            gap = min((abs(y - o) for o in others if o is not None), default=1e6)
            scored.append((gap, px, y))
        scored.sort(key=lambda z: (-z[0], z[1]))
        options.append(scored or [(0.0, curve[len(curve) // 2][0], curve[len(curve) // 2][1])])

    # Most constrained first: a curve whose best option is already cramped has the least room to
    # give up, so it chooses before the ones that can sit almost anywhere.
    order = sorted(range(len(curves)), key=lambda i: options[i][0][0])
    placed = [None] * len(curves)
    for i in order:
        chosen = None
        for gap, px, py in options[i]:
            if all(abs(px - q[0]) >= min_dx or abs(py - q[1]) >= min_gap
                   for q in placed if q is not None):
                chosen = (px, py)
                break
        if chosen is None:
            # Nothing on this curve is clear of everything already placed, so take its best
            # anchor and lift the label until it is. Rare, and better than dropping the label.
            _, px, py = options[i][0]
            while any(abs(px - q[0]) < min_dx and abs(py - q[1]) < min_gap
                      for q in placed if q is not None):
                py -= min_gap
            chosen = (px, py)
        placed[i] = chosen
    return placed


def series_plot(parts, ax, series, label_at="spread", dash=None):
    """One line per named series, each labeled on the curve rather than in a legend box."""
    anchors = place_labels(ax, series) if label_at == "spread" else None
    for i, (name, points) in enumerate(series):
        cls = f"s{i % 8}"
        parts.append(ax.path([p[0] for p in points], [p[1] for p in points], cls, 1.9, dash))
        if anchors is not None:
            px, py = anchors[i]
        elif label_at == "max":
            bx, by = max(points, key=lambda p: p[1])
            px, py = ax.x(bx), ax.y(by)
        else:
            px, py = ax.x(points[-1][0]), ax.y(points[-1][1])
        parts.append(text(px, py - 7, name, f"t{i % 8}", 10, "middle", "600"))


