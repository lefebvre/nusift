"""Regenerate the scenario figures in docs/scenarios.md.

    python docs/figures/make_scenario_figures.py        # numpy only

Every figure here is drawn from verbatim CLI output committed under data/, regenerated by
data/make_data.sh. Nothing is typed in from memory and nothing is redrawn by hand: if a figure
says the decay heat crosses a kilowatt at 305 days, that number came out of `nusift when`.

The split from make_figures.py is by PURPOSE rather than by machinery. That file illustrates the
METHOD -- what an interval integral is, how a subtraction loses its digits, what the air
coefficients do -- and its figures belong beside the equations. These illustrate the CAPABILITIES:
one per subcommand, each showing what the command is for on a source it actually suits. Both draw
through svgplot.py, so the two sets cannot drift into different visual languages.

The chart primitives at the top are shared by most of the nineteen figures, because nineteen
bespoke plotting functions would be nineteen chances for two bar charts to disagree about where
their labels go.
"""

from __future__ import annotations

import csv
import math
from pathlib import Path

from svgplot import Axes, circle, line, polyline, rect, svg, text

OUT = Path(__file__).resolve().parent
DATA = OUT / "data"

# Decade ticks and their spellings, used by every log-time axis here so that two figures over
# the same window cannot label it differently.
DECADES = [
    (1.0, "1 s"), (60.0, "1 m"), (3600.0, "1 h"), (86400.0, "1 d"), (864000.0, "10 d"),
    (3.15576e7, "1 y"), (3.15576e8, "10 y"), (3.15576e9, "100 y"), (3.15576e10, "1 ky"),
]


def read_csv(name):
    with (DATA / name).open(newline="", encoding="utf-8") as handle:
        return list(csv.DictReader(handle))


def number(row, field, default=0.0):
    """A CSV cell as a float, with an EMPTY cell meaning absent rather than zero.

    The reports write an empty field where a quantity was not stated -- no evaluated sigma, no
    end time on an instantaneous row -- precisely so that "none stated" and "stated as zero"
    stay distinguishable. Reading them back has to preserve that or the figures would quietly
    assert the thing the format went to trouble to avoid.
    """
    raw = (row.get(field) or "").strip()
    return float(raw) if raw else default


def read_text(name):
    return (DATA / name).read_text(encoding="utf-8")


def si(value, digits=3):
    """A number as a report would print it: three significant figures, exponent when needed."""
    if value == 0:
        return "0"
    exponent = math.floor(math.log10(abs(value)))
    if -3 <= exponent < 5:
        return f"{value:,.{max(0, digits - 1 - exponent)}f}".rstrip("0").rstrip(".")
    mantissa = value / 10.0**exponent
    return f"{mantissa:.2f}e{exponent}"


def duration(seconds):
    """Seconds as the CLI spells them, so a figure and a report agree about when something is."""
    for size, unit in ((3.15576e7, "y"), (86400.0, "d"), (3600.0, "h"), (60.0, "m")):
        if seconds >= size:
            return f"{seconds / size:.3g} {unit}"
    return f"{seconds:.3g} s"


def time_axis(ax, lo, hi):
    keep = [(v, l) for v, l in DECADES if lo <= v <= hi]
    return ax.vgrid([v for v, _ in keep], [l for _, l in keep])


def header(parts, ax, title, subtitle=None):
    parts.append(text(ax.left, 26, title, "ink", 13, "start", "600"))
    if subtitle:
        parts.append(text(ax.left, 44, subtitle, "muted", 11.5))


def notes(parts, ax, lines, top=None, width=11.5):
    """Caption lines under a figure. Returns the y of the last one, so a caller can size the SVG
    to its text rather than guessing a height that clips on one machine and not another."""
    y = (ax.bottom + 46) if top is None else top
    for i, entry in enumerate(lines):
        parts.append(text(ax.left, y + i * 18, entry, "ink" if i == 0 else "muted", 12 if i == 0 else width))
    return y + max(0, len(lines) - 1) * 18


def write(path, width, height, parts, title):
    path.write_text(svg(width, height, "\n".join(parts), title), encoding="utf-8")


