def figure_spectrum(path):
    """Which photon lines carry the emission, which is what a detector actually sees."""
    rows = read_csv("scenario-spectrum.csv")

    def line_energy(row):
        # The contributor label for a line aggregate is "<nuclide> <energy> keV"; the energy is
        # what orders the spectrum, so it is parsed rather than assumed to be the rank order.
        for token in row["contributor"].replace("keV", "").split():
            try:
                return float(token)
            except ValueError:
                continue
        return 0.0

    rows = sorted(rows, key=line_energy)
    energies = [line_energy(r) for r in rows]
    values = [float(r["value"]) for r in rows]

    w, h = 900, 470
    ax = Axes(84, 820, 84, 300, (0, max(energies) * 1.08), (0, max(values) * 1.25))
    parts = []
    grid = [max(values) * f for f in (0.25, 0.5, 0.75, 1.0)]
    parts += ax.hgrid(grid, [si(g) for g in grid])
    ticks = [t for t in (0, 250, 500, 750, 1000, 1250, 1500, 2000, 2500) if t <= max(energies) * 1.08]
    parts += ax.vgrid(ticks, [f"{t:g}" for t in ticks])

    for i, (energy, value) in enumerate(zip(energies, values)):
        x = ax.x(energy)
        parts.append(line(x, ax.bottom, x, ax.y(value), f"s{i % 8}", 2.4))
        parts.append(circle(x, ax.y(value), 2.6, f"t{i % 8}"))
    # Only the strongest few are labeled: a spectrum with fourteen labels is a spectrum nobody
    # can read, and the ones that matter are the ones a detector will resolve first.
    for row, energy, value in sorted(zip(rows, energies, values), key=lambda z: -z[2])[:5]:
        parts.append(text(ax.x(energy), ax.y(value) - 9, row["contributor"], "ink", 10, "middle", "600"))
    parts += ax.frame()

