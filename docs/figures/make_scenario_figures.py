    parts.append(text(left, y + 58, "Every sheet is carried FORWARD and none backward, which is a refusal rather than a limitation. Un-growing a daughter is an", "muted", 11.5))
    parts.append(text(left, y + 74, "inverse problem with no unique answer, so an epoch earlier than an assay is rejected rather than answered with one of them.", "muted", 11.5))
    write(path, w, y + 94, parts, "Assays from several dates reconciled to one")
    print(f"  reconcile: {len(sheets)} sheets in, {len(merged)} nuclides out, {len(grown)} never measured")


